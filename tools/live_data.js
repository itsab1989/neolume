'use strict';
/* Senderdaten fuer den Helfer (SPEC LIVE-10): erzeugt installer/neosetup/livedata.py aus src/live/channels.js.
 * Der Helfer setzt nur fuer Sender mit getrenntem Ton (sep) Bild und Ton zusammen und ruft nur die Hosts genau dieser Sender
 * ab: HOSTS = die Hosts ihrer festen Master-Adressen, exakt, ohne Unter-Domains (Review 05.11. L3; nachgeprueft 05.11.2026:
 * ARD-Schnittstelle, Master-, Varianten-, Tonlisten und Stuecke aller 27 Sender liegen auf dem Host der festen Adresse). Jeder
 * Host muss in `hosts` der App erlaubt sein, sonst bricht die Erzeugung ab. Kein Kopieren von Hand: `npm run spec` schreibt die Datei, `npm run spec:check`/`npm test` meldet sie als veraltet.
 * Aufruf allein: node tools/live_data.js [--check] */
var fs = require('fs'), path = require('path'), vm = require('vm');
var ROOT = path.join(__dirname, '..'), SRC = 'src/live/channels.js', OUT = 'installer/neosetup/livedata.py';

function data() {
  var ctx = { N: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, SRC), 'utf8'), ctx, { filename: SRC });
  return ctx.N.liveData;
}
function py(v) { return JSON.stringify(v); }   // ASCII-JSON ist gueltiges Python (Strings, Listen; keine null/true/false)
/* D: Senderdaten (Standard: src/live/channels.js; Tests geben eine erweiterte Liste, z. B. eine neue Region) */
function render(D) {
  D = D || data();
  var lines = [], hosts = [];
  var chans = D.channels.filter(function (ch) { return ch.sep && !ch.fmp4; });   // nur MPEG-TS mit getrenntem Ton
  chans.forEach(function (ch) {
    var m = /^https:\/\/([a-z0-9.-]+)\//.exec(ch.url), h = m && m[1];
    if (!h || !D.hosts.some(function (x) { return h === x || h.slice(-x.length - 1) === '.' + x; }))
      throw new Error('live_data: ' + ch.id + ': host of ' + ch.url + ' not in hosts');
    if (hosts.indexOf(h) < 0) hosts.push(h);
  });
  hosts.sort();
  lines.push('"""GENERATED by tools/live_data.js from ' + SRC + ' - do not edit; run `npm run spec`.',
    '',
    'Channels whose sound comes as a separate HLS rendition (data field `sep`) - the only ones the helper joins for the 2014 TV',
    '(SPEC LIVE-10) - and the hosts it may fetch from: exactly the hosts of these channels\' addresses, no sub-domains.',
    'CHANNELS: id -> {"url": fixed master playlist, "ard": [partner, item id] of the ARD Mediathek page gateway (optional)}."""',
    '',
    'VERSION = ' + py(D.v),
    'HOSTS = (' + hosts.map(py).join(', ') + ',)',
    'CHANNELS = {');
  chans.forEach(function (ch) {
    var o = '    ' + py(ch.id) + ': {"url": ' + py(ch.url);
    if (ch.api && ch.api.t === 'ard') o += ', "ard": [' + py(ch.api.p) + ', ' + py(ch.api.id) + ']';
    lines.push(o + '},');
  });
  lines.push('}', '');
  return lines.join('\n').replace(/[^\x00-\x7f]/g, function (c) { return '\\u' + ('000' + c.charCodeAt(0).toString(16)).slice(-4); });
}
/* -> Liste veralteter Dateien (leer = aktuell) */
function stale() {
  var f = path.join(ROOT, OUT), cur = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
  return cur === render() ? [] : [OUT];
}
function write() {
  if (!stale().length) return [];
  fs.writeFileSync(path.join(ROOT, OUT), render());
  return [OUT];
}
module.exports = { render: render, stale: stale, write: write, data: data, OUT: OUT };
if (require.main === module) {
  if (process.argv.indexOf('--check') >= 0) {
    var s = stale();
    if (s.length) { console.error(OUT + ': stale, run `node tools/live_data.js` (or `npm run spec`)'); process.exit(1); }
    console.log(OUT + ' up to date');
  } else console.log(write().length ? 'written: ' + OUT : OUT + ' up to date');
}
